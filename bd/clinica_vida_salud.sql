-- =====================================================================
-- Clínica Vida Salud - Sistema de gestión de citas médicas
-- PostgreSQL: creación de tablas y relaciones (24 tablas)
-- Parte 1: tablas con PK, UNIQUE, NOT NULL, DEFAULT y CHECK
-- Parte 2: llaves foráneas (ON DELETE/UPDATE RESTRICT)
-- =====================================================================

BEGIN;

-- =====================================================================
-- PARTE 1: TABLAS
-- =====================================================================

-- ---------- Personas ----------
CREATE TABLE datos_personales (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci               VARCHAR(30) UNIQUE,
    nombres          VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    sexo             VARCHAR(30),
    telefono         VARCHAR(30) NOT NULL,
    correo           VARCHAR(254),
    direccion        VARCHAR(250),
    CONSTRAINT ck_dp_ci        CHECK (ci IS NULL OR btrim(ci) <> ''),
    CONSTRAINT ck_dp_nombres   CHECK (btrim(nombres) <> ''),
    CONSTRAINT ck_dp_apellidos CHECK (btrim(apellidos) <> ''),
    CONSTRAINT ck_dp_telefono  CHECK (btrim(telefono) <> ''),
    CONSTRAINT ck_dp_correo    CHECK (correo IS NULL OR btrim(correo) <> '')
);
CREATE UNIQUE INDEX ux_datos_personales_correo
    ON datos_personales (lower(btrim(correo)));

CREATE TABLE paciente (
    id             BIGINT PRIMARY KEY,
    codigo         VARCHAR(20) NOT NULL UNIQUE,
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_paciente_codigo CHECK (btrim(codigo) <> '')
);

CREATE TABLE medico (
    id                       BIGINT PRIMARY KEY,
    codigo                   VARCHAR(20) NOT NULL UNIQUE,
    nro_registro_profesional VARCHAR(50) NOT NULL UNIQUE,
    activo                   BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_medico_codigo   CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_medico_registro CHECK (btrim(nro_registro_profesional) <> '')
);

CREATE TABLE personal (
    id            BIGINT PRIMARY KEY,
    fecha_ingreso DATE NOT NULL,
    activo        BOOLEAN NOT NULL DEFAULT TRUE
);

-- ---------- Seguridad y auditoría ----------
CREATE TABLE perfil (
    id          SMALLINT PRIMARY KEY,
    nombre      VARCHAR(30) NOT NULL UNIQUE,
    descripcion TEXT,
    activo      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_perfil_nombre
        CHECK (nombre IN ('administrador', 'recepcionista', 'medico', 'paciente'))
);

CREATE TABLE usuario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    datos_personales_id BIGINT NOT NULL UNIQUE,
    perfil_id           SMALLINT NOT NULL,
    nombre_usuario      VARCHAR(50) NOT NULL,
    contrasena_hash     VARCHAR(255) NOT NULL,
    activo              BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_registro      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_usuario_nombre
        CHECK (btrim(nombre_usuario) <> '' AND position('@' IN nombre_usuario) = 0),
    CONSTRAINT ck_usuario_hash CHECK (btrim(contrasena_hash) <> '')
);
CREATE UNIQUE INDEX ux_usuario_nombre_usuario
    ON usuario (lower(btrim(nombre_usuario)));

CREATE TABLE privilegio (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(80) NOT NULL UNIQUE,
    descripcion TEXT,
    CONSTRAINT ck_privilegio_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE perfil_privilegio (
    perfil_id        SMALLINT NOT NULL,
    privilegio_id    BIGINT NOT NULL,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (perfil_id, privilegio_id)
);

CREATE TABLE preferencia_cuenta (
    usuario_id                 BIGINT PRIMARY KEY,
    notificaciones             BOOLEAN NOT NULL DEFAULT TRUE,
    mostrar_contacto_al_medico BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE bitacora (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT NOT NULL,
    accion      VARCHAR(80) NOT NULL,
    entidad     VARCHAR(60) NOT NULL,
    registro_id BIGINT NOT NULL,
    fecha_hora  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip          INET,
    CONSTRAINT ck_bitacora_accion  CHECK (btrim(accion) <> ''),
    CONSTRAINT ck_bitacora_entidad CHECK (btrim(entidad) <> '')
);

-- ---------- Perfil clínico del paciente ----------
CREATE TABLE ficha_medica (
    paciente_id                BIGINT PRIMARY KEY,
    tipo_sangre                VARCHAR(3),
    alergias                   TEXT,
    intolerancias_medicamentos TEXT,
    enfermedades_cronicas      TEXT,
    medicamentos_actuales      TEXT,
    antecedentes_personales    TEXT,
    antecedentes_familiares    TEXT,
    fecha_actualizacion        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizada_por            BIGINT NOT NULL,
    CONSTRAINT ck_ficha_tipo_sangre
        CHECK (tipo_sangre IS NULL
               OR tipo_sangre IN ('A+','A-','B+','B-','AB+','AB-','O+','O-'))
);

CREATE TABLE contacto_emergencia (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id BIGINT NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    parentesco  VARCHAR(50) NOT NULL,
    telefono    VARCHAR(30) NOT NULL,
    CONSTRAINT ck_contacto_nombre     CHECK (btrim(nombre) <> ''),
    CONSTRAINT ck_contacto_parentesco CHECK (btrim(parentesco) <> ''),
    CONSTRAINT ck_contacto_telefono   CHECK (btrim(telefono) <> '')
);

-- ---------- Especialidades y agenda del médico ----------
CREATE TABLE especialidad (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL,
    descripcion TEXT,
    activo      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_especialidad_nombre CHECK (btrim(nombre) <> '')
);
CREATE UNIQUE INDEX ux_especialidad_nombre
    ON especialidad (lower(btrim(nombre)));

CREATE TABLE medico_especialidad (
    medico_id        BIGINT NOT NULL,
    especialidad_id  BIGINT NOT NULL,
    fecha_asignacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activo           BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (medico_id, especialidad_id)
);

CREATE TABLE horario_atencion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id         BIGINT NOT NULL,
    dia_semana        SMALLINT NOT NULL,
    hora_inicio       TIME NOT NULL,
    hora_fin          TIME NOT NULL,
    duracion_cita_min SMALLINT NOT NULL DEFAULT 15,
    vigente_desde     DATE NOT NULL,
    vigente_hasta     DATE,
    activo            BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_horario_dia      CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_horario_horas    CHECK (hora_fin > hora_inicio),
    CONSTRAINT ck_horario_duracion CHECK (duracion_cita_min > 0),
    CONSTRAINT ck_horario_vigencia CHECK (vigente_hasta IS NULL OR vigente_hasta >= vigente_desde)
);

CREATE TABLE bloqueo_agenda (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id BIGINT NOT NULL,
    fecha     DATE NOT NULL,
    motivo    VARCHAR(250) NOT NULL,
    CONSTRAINT uq_bloqueo_medico_fecha UNIQUE (medico_id, fecha),
    CONSTRAINT ck_bloqueo_motivo CHECK (btrim(motivo) <> '')
);

-- ---------- Citas ----------
CREATE TABLE estado_cita (
    id          SMALLINT PRIMARY KEY,
    nombre      VARCHAR(20) NOT NULL UNIQUE,
    descripcion TEXT
);

CREATE TABLE cita_medica (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(20) NOT NULL UNIQUE,
    paciente_id      BIGINT NOT NULL,
    medico_id        BIGINT NOT NULL,
    especialidad_id  BIGINT NOT NULL,
    estado_cita_id   SMALLINT NOT NULL DEFAULT 1,
    inicio           TIMESTAMPTZ NOT NULL,
    fin              TIMESTAMPTZ NOT NULL,
    motivo           TEXT,
    modalidad        VARCHAR(20) NOT NULL DEFAULT 'presencial',
    importe_acordado NUMERIC(12,2) NOT NULL,
    moneda           VARCHAR(3) NOT NULL DEFAULT 'BOB',
    creada_por       BIGINT NOT NULL,
    fecha_creacion   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cita_codigo    CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_cita_intervalo CHECK (fin > inicio),
    CONSTRAINT ck_cita_modalidad CHECK (modalidad IN ('presencial', 'virtual')),
    CONSTRAINT ck_cita_importe   CHECK (importe_acordado >= 0),
    CONSTRAINT ck_cita_moneda    CHECK (moneda ~ '^[A-Z]{3}$')
);

CREATE TABLE historial_cita (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id            BIGINT NOT NULL,
    usuario_id         BIGINT NOT NULL,
    tipo_evento        VARCHAR(20) NOT NULL,
    estado_anterior_id SMALLINT,
    estado_nuevo_id    SMALLINT NOT NULL,
    inicio_anterior    TIMESTAMPTZ,
    fin_anterior       TIMESTAMPTZ,
    inicio_nuevo       TIMESTAMPTZ NOT NULL,
    fin_nuevo          TIMESTAMPTZ NOT NULL,
    observacion        TEXT,
    fecha_hora         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_hist_tipo  CHECK (tipo_evento IN ('creacion', 'cambio_estado', 'reprogramacion')),
    CONSTRAINT ck_hist_nuevo CHECK (fin_nuevo > inicio_nuevo),
    CONSTRAINT ck_hist_coherencia CHECK (
        (tipo_evento = 'creacion'
            AND estado_anterior_id IS NULL
            AND inicio_anterior IS NULL AND fin_anterior IS NULL)
        OR
        (tipo_evento = 'cambio_estado'
            AND estado_anterior_id IS NOT NULL
            AND estado_anterior_id <> estado_nuevo_id
            AND inicio_anterior IS NULL AND fin_anterior IS NULL)
        OR
        (tipo_evento = 'reprogramacion'
            AND estado_anterior_id IS NOT NULL
            AND estado_anterior_id = estado_nuevo_id
            AND inicio_anterior IS NOT NULL AND fin_anterior IS NOT NULL
            AND fin_anterior > inicio_anterior
            AND (inicio_anterior, fin_anterior) IS DISTINCT FROM (inicio_nuevo, fin_nuevo))
    ),
    -- Reprogramar o cancelar (cambio a estado 4) exige motivo
    CONSTRAINT ck_hist_observacion CHECK (
        NOT (tipo_evento = 'reprogramacion'
             OR (tipo_evento = 'cambio_estado' AND estado_nuevo_id = 4))
        OR (observacion IS NOT NULL AND btrim(observacion) <> '')
    )
);

-- ---------- Atención clínica ----------
CREATE TABLE consulta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id       BIGINT NOT NULL UNIQUE,
    fecha_hora    TIMESTAMPTZ NOT NULL,
    observaciones TEXT,
    diagnostico   TEXT,
    CONSTRAINT ck_consulta_contenido CHECK (
        COALESCE(btrim(observaciones), '') <> '' OR COALESCE(btrim(diagnostico), '') <> ''
    )
);

CREATE TABLE tratamiento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id  BIGINT NOT NULL,
    indicaciones TEXT NOT NULL,
    fecha_inicio DATE,
    fecha_fin    DATE,
    CONSTRAINT ck_trat_indicaciones CHECK (btrim(indicaciones) <> ''),
    CONSTRAINT ck_trat_fechas CHECK (
        fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio
    )
);

CREATE TABLE estudio_laboratorio (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id        BIGINT NOT NULL,
    nombre_estudio     VARCHAR(150) NOT NULL,
    indicaciones       TEXT,
    solicitado_en      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado             VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    resultado_texto    TEXT,
    archivo_referencia VARCHAR(500),
    publicado_en       TIMESTAMPTZ,
    publicado_por      BIGINT,
    CONSTRAINT ck_estudio_nombre CHECK (btrim(nombre_estudio) <> ''),
    CONSTRAINT ck_estudio_estado CHECK (estado IN ('pendiente', 'en_proceso', 'disponible')),
    CONSTRAINT ck_estudio_publicacion CHECK (
        (estado = 'disponible'
            AND publicado_en IS NOT NULL
            AND publicado_por IS NOT NULL
            AND (COALESCE(btrim(resultado_texto), '') <> ''
                 OR COALESCE(btrim(archivo_referencia), '') <> ''))
        OR
        (estado <> 'disponible'
            AND publicado_en IS NULL
            AND publicado_por IS NULL)
    ),
    CONSTRAINT ck_estudio_fechas CHECK (publicado_en IS NULL OR publicado_en >= solicitado_en)
);

-- ---------- Pagos ----------
CREATE TABLE pasarela_pago (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_pasarela_codigo CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_pasarela_nombre CHECK (btrim(nombre) <> '')
);

CREATE TABLE pago (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id            BIGINT NOT NULL,
    pasarela_id        BIGINT NOT NULL,
    iniciado_por       BIGINT NOT NULL,
    clave_idempotencia UUID NOT NULL UNIQUE,
    referencia_externa VARCHAR(150),
    importe            NUMERIC(12,2) NOT NULL,
    moneda             VARCHAR(3) NOT NULL,
    estado             VARCHAR(20) NOT NULL DEFAULT 'pendiente',
    creado_en          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    verificado_en      TIMESTAMPTZ,
    CONSTRAINT uq_pago_pasarela_referencia UNIQUE (pasarela_id, referencia_externa),
    CONSTRAINT ck_pago_importe CHECK (importe > 0),
    CONSTRAINT ck_pago_moneda  CHECK (moneda ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_pago_estado  CHECK (estado IN ('pendiente','aprobado','rechazado','cancelado','reembolsado')),
    CONSTRAINT ck_pago_referencia CHECK (referencia_externa IS NULL OR btrim(referencia_externa) <> ''),
    CONSTRAINT ck_pago_aprobado CHECK (
        estado NOT IN ('aprobado', 'reembolsado')
        OR (referencia_externa IS NOT NULL AND verificado_en IS NOT NULL)
    ),
    CONSTRAINT ck_pago_verificacion CHECK (verificado_en IS NULL OR verificado_en >= creado_en)
);

-- =====================================================================
-- PARTE 2: RELACIONES (LLAVES FORÁNEAS)
-- =====================================================================

-- Herencia de datos_personales (PK compartida)
ALTER TABLE paciente ADD CONSTRAINT fk_paciente_persona
    FOREIGN KEY (id) REFERENCES datos_personales (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE medico ADD CONSTRAINT fk_medico_persona
    FOREIGN KEY (id) REFERENCES datos_personales (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE personal ADD CONSTRAINT fk_personal_persona
    FOREIGN KEY (id) REFERENCES datos_personales (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Seguridad
ALTER TABLE usuario ADD CONSTRAINT fk_usuario_persona
    FOREIGN KEY (datos_personales_id) REFERENCES datos_personales (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE usuario ADD CONSTRAINT fk_usuario_perfil
    FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE perfil_privilegio ADD CONSTRAINT fk_pp_perfil
    FOREIGN KEY (perfil_id) REFERENCES perfil (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE perfil_privilegio ADD CONSTRAINT fk_pp_privilegio
    FOREIGN KEY (privilegio_id) REFERENCES privilegio (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE preferencia_cuenta ADD CONSTRAINT fk_pref_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE bitacora ADD CONSTRAINT fk_bitacora_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Perfil clínico
ALTER TABLE ficha_medica ADD CONSTRAINT fk_ficha_paciente
    FOREIGN KEY (paciente_id) REFERENCES paciente (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE ficha_medica ADD CONSTRAINT fk_ficha_actualizada_por
    FOREIGN KEY (actualizada_por) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE contacto_emergencia ADD CONSTRAINT fk_contacto_paciente
    FOREIGN KEY (paciente_id) REFERENCES paciente (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Médicos, especialidades y agenda
ALTER TABLE medico_especialidad ADD CONSTRAINT fk_me_medico
    FOREIGN KEY (medico_id) REFERENCES medico (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE medico_especialidad ADD CONSTRAINT fk_me_especialidad
    FOREIGN KEY (especialidad_id) REFERENCES especialidad (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE horario_atencion ADD CONSTRAINT fk_horario_medico
    FOREIGN KEY (medico_id) REFERENCES medico (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE bloqueo_agenda ADD CONSTRAINT fk_bloqueo_medico
    FOREIGN KEY (medico_id) REFERENCES medico (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Citas
ALTER TABLE cita_medica ADD CONSTRAINT fk_cita_paciente
    FOREIGN KEY (paciente_id) REFERENCES paciente (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE cita_medica ADD CONSTRAINT fk_cita_medico_especialidad
    FOREIGN KEY (medico_id, especialidad_id)
    REFERENCES medico_especialidad (medico_id, especialidad_id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE cita_medica ADD CONSTRAINT fk_cita_estado
    FOREIGN KEY (estado_cita_id) REFERENCES estado_cita (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE cita_medica ADD CONSTRAINT fk_cita_creada_por
    FOREIGN KEY (creada_por) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

ALTER TABLE historial_cita ADD CONSTRAINT fk_hist_cita
    FOREIGN KEY (cita_id) REFERENCES cita_medica (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE historial_cita ADD CONSTRAINT fk_hist_usuario
    FOREIGN KEY (usuario_id) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE historial_cita ADD CONSTRAINT fk_hist_estado_anterior
    FOREIGN KEY (estado_anterior_id) REFERENCES estado_cita (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE historial_cita ADD CONSTRAINT fk_hist_estado_nuevo
    FOREIGN KEY (estado_nuevo_id) REFERENCES estado_cita (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Atención clínica
ALTER TABLE consulta ADD CONSTRAINT fk_consulta_cita
    FOREIGN KEY (cita_id) REFERENCES cita_medica (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE tratamiento ADD CONSTRAINT fk_trat_consulta
    FOREIGN KEY (consulta_id) REFERENCES consulta (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE estudio_laboratorio ADD CONSTRAINT fk_estudio_consulta
    FOREIGN KEY (consulta_id) REFERENCES consulta (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE estudio_laboratorio ADD CONSTRAINT fk_estudio_publicado_por
    FOREIGN KEY (publicado_por) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

-- Pagos
ALTER TABLE pago ADD CONSTRAINT fk_pago_cita
    FOREIGN KEY (cita_id) REFERENCES cita_medica (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE pago ADD CONSTRAINT fk_pago_pasarela
    FOREIGN KEY (pasarela_id) REFERENCES pasarela_pago (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE pago ADD CONSTRAINT fk_pago_iniciado_por
    FOREIGN KEY (iniciado_por) REFERENCES usuario (id) ON DELETE RESTRICT ON UPDATE RESTRICT;

COMMIT;

